import assert from 'node:assert/strict';
import {randomUUID} from 'node:crypto';
import {PrismaClient} from '@prisma/client';
import {ReservationService,estimateReservation} from '../src/services/billing/reservation-service.ts';
import {TokenService} from '../src/services/token/token-service.ts';
if(!process.env.DATABASE_URL?.includes('/billing_test')) throw Error('Only isolated billing_test database permitted');
const p=new PrismaClient(),svc=new ReservationService(p),suffix=randomUUID().slice(0,8);
const alias={alias:'test',inputPrice:1,outputPrice:2,cacheReadPrice:0.1,cacheWrite5mPrice:1,cacheWrite1hPrice:1,maxContext:20000};
const body={model:'test',prompt:'A'.repeat(128),max_tokens:5};
const amount=estimateReservation(alias,body,1,1);
const user=await p.user.create({data:{username:'billing_'+suffix,passwordHash:'not-a-password',inviteCode:suffix,quota:amount}});
const group=await p.keyGroup.create({data:{name:'g_'+suffix,userId:user.id,quota:amount*100n}});
const key=await p.apiKey.create({data:{userId:user.id,keyGroupId:group.id,name:'test',keyHash:randomUUID(),keyPrefix:'test',quota:-1n}});
const key2=await p.apiKey.create({data:{userId:user.id,keyGroupId:group.id,name:'test2',keyHash:randomUUID(),keyPrefix:'test',quota:-1n}});
const channel=await p.channel.create({data:{name:'test_'+suffix,type:'openai',models:[]}});
const multipliers={[channel.id]:1};
const usage={inputTokens:100,outputTokens:10,cacheCreationTokens:0,cacheReadTokens:0};
const zero={inputTokens:0,outputTokens:0,cacheCreationTokens:0,cacheReadTokens:0};
const context=id=>({requestId:id,model:'test',upstreamModel:'test',channelId:channel.id,nodeId:1n,endpoint:'/v1/chat/completions',startedAt:new Date()});
try {
  const ids=Array.from({length:16},()=>randomUUID());
  const parallel=await Promise.allSettled(ids.map((id,i)=>svc.reserve(id,i%2?key.id:key2.id,alias,body,multipliers)));
  assert.equal(parallel.filter(r=>r.status==='fulfilled').length,1,'one wallet cannot be oversubscribed across keys');
  const winner=parallel.find(r=>r.status==='fulfilled').value;
  await Promise.all(Array.from({length:16},()=>svc.finish(context(winner.requestId),usage,'succeeded',200)));
  assert.equal(await p.usageLedger.count({where:{userId:user.id}}),1,'one ledger per request');
  assert.equal((await p.user.findUnique({where:{id:user.id}})).usedQuota,120n);
  assert.equal((await p.keyGroup.findUnique({where:{id:group.id}})).usedQuota,120n,'images and chat share group settlement');
  assert((await svc.reconcile(user.id)).balanced);
  await p.user.update({where:{id:user.id},data:{quota:amount*100n}});
  const rejected=randomUUID();await svc.reserve(rejected,key.id,alias,body,multipliers);
  await svc.finish(context(rejected),zero,'failed',429,'upstream_429');
  assert.equal((await p.billingReservation.findUnique({where:{requestId:rejected}})).status,'released');
  assert.equal((await p.user.findUnique({where:{id:user.id}})).usedQuota,120n,'known rejection releases without charge');
  const crash=randomUUID();await svc.reserve(crash,key.id,alias,body,multipliers);
  const finalize=svc.finalize.bind(svc);svc.finalize=async()=>{throw Error('simulated process crash')};
  await assert.rejects(svc.finish(context(crash),usage,'succeeded',200),/simulated/);svc.finalize=finalize;
  assert.equal((await p.billingReservation.findUnique({where:{requestId:crash}})).status,'pending');
  await svc.recover();await svc.recover();
  assert.equal((await p.user.findUnique({where:{id:user.id}})).usedQuota,240n,'durable replay exactly once');
  await p.keyGroup.update({where:{id:group.id},data:{quota:240n+amount}});
  const groupIds=[randomUUID(),randomUUID()];
  const groupRace=await Promise.allSettled(groupIds.map((id,i)=>svc.reserve(id,i?key2.id:key.id,alias,body,multipliers)));
  assert.equal(groupRace.filter(r=>r.status==="fulfilled").length,1,"shared group hold blocks competing key");
  const heldGroup=groupRace.find(r=>r.status==="fulfilled").value;
  await svc.finish(context(heldGroup.requestId),zero,"failed",429,"upstream_429");
  await p.keyGroup.update({where:{id:group.id},data:{quota:amount*100n}});
  await p.apiKey.update({where:{id:key.id},data:{dailyLimit:240n+amount}});
  const dailyId=randomUUID();await svc.reserve(dailyId,key.id,alias,body,multipliers);
  await assert.rejects(svc.reserve(randomUUID(),key.id,alias,body,multipliers),/Daily/);
  await svc.finish(context(dailyId),zero,"failed",429,"upstream_429");
  await p.apiKey.update({where:{id:key.id},data:{dailyLimit:-1n}});
  const missing=randomUUID();await svc.reserve(missing,key.id,alias,body,multipliers);
  await assert.rejects(svc.finish(context(missing),zero,'succeeded',200),/review/);
  assert.equal((await p.billingReservation.findUnique({where:{requestId:missing}})).status,'review');
  await assert.rejects(svc.reserve(randomUUID(),key2.id,alias,body,multipliers),/review/);
  assert((await svc.reconcile(user.id)).balanced);
  await svc.resolveReview(missing,"release","Confirmed test upstream did not charge",user.id);
  assert.equal((await p.billingReservation.findUnique({where:{requestId:missing}})).status,"released");
  const stale=randomUUID();await svc.reserve(stale,key.id,alias,body,multipliers);
  await p.billingReservation.update({where:{requestId:stale},data:{createdAt:new Date(Date.now()-30*60*1000)}});
  await svc.recover();
  assert.equal((await p.billingReservation.findUnique({where:{requestId:stale}})).status,"review");
  await svc.resolveReview(stale,"release","Confirmed interrupted fixture no charge",user.id);
  const frozenId=randomUUID();const mutable={...alias};await svc.reserve(frozenId,key.id,mutable,body,multipliers);mutable.inputPrice=9000;
  await svc.finish(context(frozenId),usage,"succeeded",200);
  assert.equal((await p.billingReservation.findUnique({where:{requestId:frozenId}})).charged,120n,"frozen tariff");
  const underestimated=randomUUID();await svc.reserve(underestimated,key.id,alias,body,multipliers);
  const beforeReview=(await p.user.findUniqueOrThrow({where:{id:user.id}})).usedQuota;
  await assert.rejects(svc.finish(context(underestimated),{...usage,outputTokens:10000000},"succeeded",200),/review/);
  assert.equal((await p.user.findUniqueOrThrow({where:{id:user.id}})).usedQuota,beforeReview,"estimate overrun cannot produce a negative wallet");
  await svc.resolveReview(underestimated,"release","Fixture-only overrun explicitly waived",user.id);
  const invalid=randomUUID();await svc.reserve(invalid,key.id,alias,body,multipliers);
  const beforeInvalid=(await p.user.findUniqueOrThrow({where:{id:user.id}})).usedQuota;
  await assert.rejects(svc.finish(context(invalid),{...usage,outputTokens:0.5},"succeeded",200),/review/);
  const invalidRow=await p.billingReservation.findUniqueOrThrow({where:{requestId:invalid}});
  assert.equal(invalidRow.status,"review");assert.equal(invalidRow.charged,0n);
  assert.equal((await p.user.findUniqueOrThrow({where:{id:user.id}})).usedQuota,beforeInvalid);
  assert.equal(await p.usageLedger.count({where:{requestId:invalid}}),0,"invalid usage is not a zero-charge finalized ledger");
  await svc.resolveReview(invalid,"release","Fixture invalid usage explicitly waived",user.id);
  const countBefore=await p.usageLedger.count({where:{userId:user.id}});
  assert((await svc.reconcile(user.id)).balanced);
  await new TokenService(p).delete(user.id,key.id);
  assert.equal(await p.usageLedger.count({where:{userId:user.id}}),countBefore,'revoke retains ledgers');
  assert((await p.apiKey.findUnique({where:{id:key.id}})).deletedAt);
  await p.user.update({where:{id:user.id},data:{usedQuota:{increment:1n}}});
  assert.equal((await svc.reconcile(user.id)).balanced,false,'counter drift detected');
  console.log('PASS: 16-way wallet concurrency, 16-way settlement idempotency, group accounting, failure release, crash replay, missing usage hold, key revocation and reconciliation');
} finally {
  await p.billingReservation.deleteMany({where:{userId:user.id}});
  await p.billingBaseline.deleteMany({where:{OR:[{scope:'user',accountId:user.id},{scope:'key',accountId:{in:[key.id,key2.id]}},{scope:'group',accountId:group.id}]}});
  await p.requestLog.deleteMany({where:{userId:user.id}});await p.usageLedger.deleteMany({where:{userId:user.id}});
  await p.apiKey.deleteMany({where:{userId:user.id}});await p.keyGroup.delete({where:{id:group.id}});await p.user.delete({where:{id:user.id}});await p.channel.delete({where:{id:channel.id}});await p.$disconnect();
}
